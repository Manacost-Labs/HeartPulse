import assert from 'node:assert/strict';
import { createBattlegroundLibraryResource } from '../src/modules/battlegrounds/public';
let clock = 0;
let calls = 0;
let fail = false;
const resource = createBattlegroundLibraryResource(async (kind: string, pool: string) => {
  calls++;
  if (fail) throw new Error('offline');
  return `${kind}:${pool}:${calls}`;
}, () => clock);
const first = resource.load('viewer-a', 'minion', 'current');
assert.equal(resource.load('viewer-a', 'minion', 'current'), first);
assert.equal(await first, 'minion:current:1');
assert.equal(await resource.load('viewer-a', 'minion', 'current'), 'minion:current:1');
assert.equal(calls, 1);
assert.equal(await resource.load('viewer-a', 'spell', 'current'), 'spell:current:2');
assert.equal(resource.peek('viewer-a', 'minion', 'archive'), null);
clock = 300_000;
assert.equal(resource.peek('viewer-a', 'minion', 'current'), null);
assert.equal(await resource.load('viewer-a', 'minion', 'current'), 'minion:current:3');
assert.equal(resource.peek('viewer-b', 'minion', 'current'), null);
assert.equal(resource.peek('viewer-a', 'minion', 'current'), null, 'switching viewers clears previous data');
fail = true;
await assert.rejects(resource.load('viewer-a', 'minion', 'current'), /offline/);
fail = false;
assert.equal(await resource.load('viewer-a', 'minion', 'current'), 'minion:current:5');
let resolveLate!: (value: string) => void;
const late = createBattlegroundLibraryResource(() => new Promise<string>(resolve => { resolveLate = resolve; }));
const request = late.load('a', 'minion', 'current');
late.peek('b', 'minion', 'current');
resolveLate('old viewer');
await request;
assert.equal(late.peek('a', 'minion', 'current'), null, 'late responses cannot restore a previous viewer cache');
console.log('Library request reuse, expiry, failure and viewer isolation passed');
